#!/usr/bin/env bash
# GeneralsX @build rpi5 11/10/2026
# Add a "Command & Conquer Generals Zero Hour" entry to the desktop application menu on a
# Raspberry Pi 5 (Twister OS, Raspberry Pi OS or any XDG desktop).
#
# Usage:
#   ./scripts/build/linux/install-pi5-desktop.sh            # install or update
#   ./scripts/build/linux/install-pi5-desktop.sh --remove   # remove the menu entry
#
# Installs:
#   ~/.local/bin/generalsx-zh                               launcher, logs to ~/GeneralsX/logs/zh-last-run.log
#   ~/.local/share/applications/generalsx-zh.desktop        menu entry
#   ~/.local/share/icons/generalsx-zh.png                   icon
#
# The launcher calls run-pi5-zh.sh from this checkout, so run deploy-linux-zh.sh linux-aarch64
# after each build as usual. Re-run this script if the checkout moves.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../../.." && pwd)"
RUN_SCRIPT="${SCRIPT_DIR}/run-pi5-zh.sh"
ICON_SRC="${REPO_ROOT}/assets/generalsx-zh_icon.png"

DATA_HOME="${XDG_DATA_HOME:-${HOME}/.local/share}"
BIN_DIR="${HOME}/.local/bin"
LAUNCHER="${BIN_DIR}/generalsx-zh"
DESKTOP_FILE="${DATA_HOME}/applications/generalsx-zh.desktop"
ICON_FILE="${DATA_HOME}/icons/generalsx-zh.png"

refresh_menu() {
  if command -v update-desktop-database >/dev/null 2>&1; then
    update-desktop-database "${DATA_HOME}/applications" >/dev/null 2>&1 || true
  fi
}

if [[ "${1:-}" == "--remove" ]]; then
  rm -f "${LAUNCHER}" "${DESKTOP_FILE}" "${ICON_FILE}"
  refresh_menu
  echo "Removed the Zero Hour menu entry."
  exit 0
fi

if [[ ! -x "${RUN_SCRIPT}" ]]; then
  echo "ERROR: ${RUN_SCRIPT} not found or not executable"
  exit 1
fi

mkdir -p "${BIN_DIR}" "${DATA_HOME}/applications" "${DATA_HOME}/icons"

cat > "${LAUNCHER}" <<EOF
#!/usr/bin/env bash
# Generated by ${SCRIPT_DIR}/install-pi5-desktop.sh
log_dir="\${HOME}/GeneralsX/logs"
mkdir -p "\${log_dir}"
exec "${RUN_SCRIPT}" "\$@" > "\${log_dir}/zh-last-run.log" 2>&1
EOF
chmod +x "${LAUNCHER}"

if [[ -f "${ICON_SRC}" ]]; then
  cp "${ICON_SRC}" "${ICON_FILE}"
else
  echo "WARNING: ${ICON_SRC} not found; the menu entry will have no icon"
fi

cat > "${DESKTOP_FILE}" <<EOF
[Desktop Entry]
Type=Application
Name=C&C Generals Zero Hour
GenericName=Real-time strategy
Comment=Command & Conquer Generals Zero Hour (GeneralsX, Raspberry Pi 5)
Exec=${LAUNCHER}
Icon=${ICON_FILE}
Terminal=false
Categories=Game;StrategyGame;
StartupNotify=true
EOF
chmod 644 "${DESKTOP_FILE}"

refresh_menu

echo "Installed the Zero Hour menu entry (Games > C&C Generals Zero Hour)."
echo "Launcher: ${LAUNCHER}"
echo "Each run logs to ~/GeneralsX/logs/zh-last-run.log"
